let currentLanguage = localStorage.getItem('language') || 'ru';

function t(key, params = {}) {
  let text = translations[currentLanguage]?.[key] || translations['ru'][key] || key;
  Object.keys(params).forEach(param => {
    text = text.replace(`{${param}}`, params[param]);
  });
  return text;
}

function translatePage() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      if (el.getAttribute('data-i18n-placeholder') !== null) {
        el.placeholder = translation;
      } else {
        el.value = translation;
      }
    } else if (el.tagName === 'IMG' && el.getAttribute('data-i18n-alt') !== null) {
      el.alt = translation;
    } else {
      el.innerHTML = translation;
    }
  });
  
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });
  
  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    const key = el.getAttribute('data-i18n-alt');
    el.alt = t(key);
  });
  
  const cartCountSpan = document.getElementById('cartCount');
  if (cartCountSpan) {
    const count = cartCountSpan.innerText;
    cartCountSpan.innerText = count;
  }
  
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: currentLanguage } }));
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLanguage = lang;
  localStorage.setItem('language', lang);
  translatePage();
  document.documentElement.lang = lang === 'ru' ? 'ru' : 'en';
}

